// Small builders for the generated deal SQL. Plain SQLite: no window functions, no recursive CTEs, no random();
// ranks are correlated COUNT(*)s and every loop is unrolled to a fixed count.
import { BUILD_SLOTS } from "../../shared/lshuf-constants.js";
import { lshufKeySql } from "../../shared/lshuf-key.js";

export const SEED = "(SELECT Seed FROM LShufWork_Cfg)";
export const CFG = (col) => `(SELECT ${col} FROM LShufWork_Cfg)`;

// lshufKey(seed, salt, rank) as SQL.
export const key = (salt, rankExpr) => lshufKeySql(SEED, String(salt), rankExpr);

export const q = (s) => (s == null ? "NULL" : `'${String(s).replace(/'/g, "''")}'`);

// "row b sorts before row a" for [bExpr, aExpr, desc] triples: a lexicographic strict less-than.
export function before(pairs) {
  const [[b, a, desc], ...rest] = pairs;
  const lt = desc ? `${b} > ${a}` : `${b} < ${a}`;
  if (!rest.length) return `(${lt})`;
  return `(${lt} OR (${b} = ${a} AND ${before(rest)}))`;
}

// Fill column `col` of `table` with the 0-based position of each row in its group (`group` columns), ordered by
// `order` ([column, desc] pairs, the last one unique within the group).
export function rankUpdate(table, col, group, order, where = "1 = 1") {
  const groupEq = group.map((g) => `o.${g} = ${table}.${g}`).join(" AND ") || "1 = 1";
  const cond = before(order.map(([c, desc]) => [`o.${c}`, `${table}.${c}`, desc]));
  return `UPDATE ${table} SET ${col} = (SELECT COUNT(*) FROM ${table} o WHERE ${groupEq} AND ${cond}) WHERE ${where};`;
}

export function work(name, columns) {
  return `CREATE TABLE IF NOT EXISTS ${name} (${columns});\nDELETE FROM ${name};`;
}

// Build your own leader (CONTRACTS 13, builder slots): one LShufWork_Build row per slot. BUILD_OF reads a field of
// the build that applies for `leader` (NULL when none), IS_BUILDER says one applies, BUILD_SLOT reads a field of
// slot n, and SLOTS lists the slot numbers for the unrolled per-slot steps.
export const SLOTS = Array.from({ length: BUILD_SLOTS }, (_, i) => i + 1);
export const BUILD_OF = (field, leader) =>
  `(SELECT b.${field} FROM LShufWork_Build b WHERE b.OK = 1 AND b.Leader = ${leader})`;
export const IS_BUILDER = (leader) => `EXISTS (SELECT 1 FROM LShufWork_Build b WHERE b.OK = 1 AND b.Leader = ${leader})`;
export const BUILD_SLOT = (field, n) => `(SELECT b.${field} FROM LShufWork_Build b WHERE b.Slot = ${n} AND b.OK = 1)`;
// The builds that apply whose builder is in an axis's pool.
export const BUILDS_IN = (axis, alias = "b") =>
  `LShufWork_Build ${alias} JOIN LShufWork_Pool p_${alias} ON p_${alias}.Axis = ${q(axis)} AND p_${alias}.LeaderType = ${alias}.Leader`;

export const header = (title) =>
  `-- ${title}\n-- Generated by scripts/generate/generate.mjs from shared/deal/ (workstream B). Don't edit by hand.\n`;
