// Writes data/generated/: the input groups' SQL, LShufKnownLeaders, the always-on deal SQL and the two modinfo
// fragments. Run: node scripts/generate/generate.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { INPUT_LOAD_ORDER, inputGroups, knownLeadersSql } from "./inputs.mjs";
import { prepareSql } from "./sql-prepare.mjs";
import { abilitySql } from "./sql-ability.mjs";
import { attributesSql } from "./sql-attributes.mjs";
import { biasesSql } from "./sql-biases.mjs";
import { resultsSql } from "./sql-results.mjs";
import { applySql } from "./sql-apply.mjs";
import { header } from "./sql-util.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const GEN = "data/generated";

export const KNOWN_FILE = `${GEN}/known-leaders.sql`;
// The always-on deal groups, in the order they run (LoadOrder 20100 and up).
export const DEAL_FILES = [
  { id: "lshuf-deal-prepare", file: `${GEN}/deal/deal-1-prepare.sql`, order: 20100, sql: prepareSql },
  { id: "lshuf-deal-ability", file: `${GEN}/deal/deal-2-ability.sql`, order: 20101, sql: abilitySql },
  { id: "lshuf-deal-attributes", file: `${GEN}/deal/deal-3-attributes.sql`, order: 20102, sql: attributesSql },
  { id: "lshuf-deal-biases", file: `${GEN}/deal/deal-4-biases.sql`, order: 20103, sql: biasesSql },
  { id: "lshuf-deal-results", file: `${GEN}/deal/deal-5-results.sql`, order: 20104, sql: resultsSql },
  { id: "lshuf-deal-apply", file: `${GEN}/deal/deal-6-apply.sql`, order: 20105, sql: applySql }
];

function group(id, criteria, order, file) {
  return `<ActionGroup id="${id}" scope="game" criteria="${criteria}">
	<Properties><LoadOrder>${order}</LoadOrder></Properties>
	<Actions><UpdateDatabase><Item>${file}</Item></UpdateDatabase></Actions>
</ActionGroup>`;
}

export function buildFiles() {
  const files = new Map();
  const inputs = inputGroups();
  const lower = new Set();
  for (const g of inputs) {
    if (lower.has(g.file.toLowerCase())) throw new Error(`file names differ only by case: ${g.file}`);
    lower.add(g.file.toLowerCase());
    files.set(g.file, g.sql);
  }
  files.set(KNOWN_FILE, `${header("LShufKnownLeaders, from shared/lshuf-known-leaders.js")}${knownLeadersSql()}`);
  for (const d of DEAL_FILES) files.set(d.file, d.sql());
  const criteria = inputs.map((g) => `<Criteria id="${g.id}">${g.criterion}</Criteria>`);
  const groups = [
    group("lshuf-known-leaders", "always", INPUT_LOAD_ORDER, KNOWN_FILE),
    ...inputs.map((g) => group(g.id, g.id, INPUT_LOAD_ORDER, g.file)),
    ...DEAL_FILES.map((d) => group(d.id, "always", d.order, d.file))
  ];
  const note = "<!-- Generated by scripts/generate/generate.mjs (workstream B). Don't edit by hand. -->";
  files.set(`${GEN}/modinfo-criteria.xml`, `${note}\n${criteria.join("\n")}\n`);
  files.set(`${GEN}/modinfo-groups.xml`, `${note}\n${groups.join("\n")}\n`);
  return files;
}

export function writeFiles(files, base = root) {
  for (const dir of ["seed", "options", "keep", "out", "moddedout", "notin", "modok", "deal"]) {
    fs.rmSync(path.join(base, GEN, dir), { recursive: true, force: true });
  }
  for (const [rel, text] of files) {
    const abs = path.join(base, rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, text);
  }
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const files = buildFiles();
  writeFiles(files);
  console.log(`wrote ${files.size} files under ${GEN}/`);
}
