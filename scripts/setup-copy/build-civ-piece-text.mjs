// Generates data/text-generated/lshuf-civ-piece-text.sql: one LOC_LSHUF_CIVPIECE_<PieceId> row per civilization
// bullet piece (data/mapping/lshuf-civ-mapping.sql) in every language the localization database holds, cut from
// each ability's live description with the splitBullets() rule (shared/lshuf-text.js), BulletCount-aware. The
// description key per piece is the mapping's own (the civilization's age key where the game keeps one per age).
//
//   node scripts/setup-copy/build-civ-piece-text.mjs [--loc PATH] [--no-check]
//
// The check loads the output twice into a copy of the localization database and compares every English piece with
// bulletAt() in JS.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { DatabaseSync } from "node:sqlite";
import { bulletAt } from "../../shared/lshuf-text.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const args = process.argv.slice(2);
const argOf = (name, fallback) => (args.includes(name) ? args[args.indexOf(name) + 1] : fallback);
const LOC_DB = argOf("--loc", path.join(ROOT, "tests", "fixtures", "source-db", "localization-copy.sqlite"));
const MAPPING = path.join(ROOT, "data/mapping/lshuf-civ-mapping.sql");
const OUT = path.join(ROOT, "data/text-generated/lshuf-civ-piece-text.sql");

const LI = "'[LI]'";
const WS = "' ' || char(9) || char(10) || char(13)";
const quote = (s) => `'${String(s).replace(/'/g, "''")}'`;
const AFTER = `substr(Text, instr(Text, ${LI}) + 4)`;
const BODY = `CASE WHEN instr(${AFTER}, '[/BLIST]') > 0 THEN substr(${AFTER}, 1, instr(${AFTER}, '[/BLIST]') - 1) `
  + `ELSE ${AFTER} END`;
const SEG = `substr(rest, 1, instr(rest, ${LI}) - 1)`;

function pieceStatement(piece) {
  const first = Number(piece.BulletIndex);
  const last = first + Math.max(1, Number(piece.BulletCount || 1)) - 1;
  return [
    `-- ${piece.PieceId}: bullet${last > first ? `s ${first}-${last}` : ` ${first}`} of ${piece.DescriptionKey}`,
    "WITH RECURSIVE seg(Language, rest, piece, n) AS (",
    `  SELECT Language, (${BODY}) || ${LI}, NULL, 0 FROM LocalizedText`,
    `  WHERE Tag = ${quote(piece.DescriptionKey)} AND instr(Text, ${LI}) > 0`,
    "  UNION ALL",
    `  SELECT Language, substr(rest, instr(rest, ${LI}) + 4), trim(${SEG}, ${WS}),`,
    `    n + (trim(${SEG}, ${WS}) <> '')`,
    `  FROM seg WHERE instr(rest, ${LI}) > 0`,
    ")",
    "INSERT OR REPLACE INTO LocalizedText (Language, Tag, Text)",
    `SELECT Language, ${quote(`LOC_LSHUF_CIVPIECE_${piece.PieceId}`)}, group_concat(piece, '[N]') FROM`,
    `  (SELECT Language, piece, n FROM seg WHERE n BETWEEN ${first} AND ${last} AND piece <> '' ORDER BY Language, n)`,
    "GROUP BY Language;"
  ].join("\n");
}

function pieces() {
  const db = new DatabaseSync(":memory:");
  db.exec(fs.readFileSync(MAPPING, "utf8"));
  const rows = db.prepare("SELECT PieceId, BulletIndex, BulletCount, DescriptionKey FROM LShufCivMapping "
    + "WHERE Kind = 'bullet' AND BulletIndex IS NOT NULL AND DescriptionKey IS NOT NULL ORDER BY PieceId").all();
  db.close();
  return rows;
}

function check(sqlText, list) {
  const tmp = path.join(os.tmpdir(), `lshuf-civ-piece-text-${process.pid}.sqlite`);
  fs.copyFileSync(LOC_DB, tmp);
  const db = new DatabaseSync(tmp);
  try {
    db.exec(sqlText);
    db.exec(sqlText);
    const get = db.prepare("SELECT Text FROM LocalizedText WHERE Language = ? AND Tag = ?");
    const rows = db.prepare("SELECT COUNT(*) AS n FROM LocalizedText WHERE Tag LIKE 'LOC_LSHUF_CIVPIECE_%'").get().n;
    let same = 0;
    const wrong = [];
    for (const p of list) {
      const source = get.get("en_US", p.DescriptionKey)?.Text;
      const count = Math.max(1, Number(p.BulletCount || 1));
      const parts = [];
      for (let i = 0; i < count; i++) parts.push(bulletAt(source, Number(p.BulletIndex) + i));
      const want = parts.filter(Boolean).join("[N]");
      const got = get.get("en_US", `LOC_LSHUF_CIVPIECE_${p.PieceId}`)?.Text || "";
      if (want === got) same++;
      else wrong.push(`${p.PieceId}: SQL ${JSON.stringify(got.slice(0, 60))} vs JS ${JSON.stringify(want.slice(0, 60))}`);
    }
    return { same, wrong, rows };
  } finally {
    db.close();
    fs.rmSync(tmp, { force: true });
  }
}

function main() {
  const list = pieces();
  const header = [
    "-- Generated by scripts/setup-copy/build-civ-piece-text.mjs; don't edit by hand. Rerun after the civilization",
    "-- mapping changes. One row per civilization bullet piece per language, cut from the live description with the",
    "-- splitBullets() rule (shared/lshuf-text.js). Loaded by UpdateText."
  ].join("\n");
  const sqlText = `${header}\n\n${list.map(pieceStatement).join("\n\n")}\n`;
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, sqlText);
  console.log(`wrote ${path.relative(ROOT, OUT)}: ${list.length} pieces from the civilization mapping`);
  if (args.includes("--no-check")) return 0;
  const result = check(sqlText, list);
  console.log(`check: ${result.rows} LOC_LSHUF_CIVPIECE rows after loading twice; ${result.same} of ${list.length} English pieces match`);
  for (const w of result.wrong.slice(0, 20)) console.log(`  differs: ${w}`);
  return result.wrong.length ? 1 : 0;
}

process.exitCode = main();
