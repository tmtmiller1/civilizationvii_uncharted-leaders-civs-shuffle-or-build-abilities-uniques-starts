// Writes text/agenda/<locale>.xml: the game's own agenda text (LOC_DIPLOMACY_AGENDA_*: name, description, likes,
// dislikes) copied out of the base game and every DLC, in every language the game ships, for the shell.
//
//   node scripts/setup-copy/build-agenda-text.mjs
//
// The game loads DiplomacyText.xml and the DLC leaders' agenda rows in the game scope only, so in the shell
// Locale.compose("LOC_DIPLOMACY_AGENDA_GUANXI_NAME") gives the key back and the AI behavior cards had nothing to
// say. These files load in the mod's shell group under the game's own tags (scripts/build-modinfo.mjs lists them),
// so the cards read what the diplomacy screen reads. Rerun after a game update or a new DLC.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { RESOURCES } from "../mapping/civ-age-source.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const OUT_DIR = path.join(ROOT, "text", "agenda");
const TAG = /^LOC_DIPLOMACY_AGENDA_/;

// Every module folder: base-standard, the ages and each DLC's modules folder.
function moduleDirs() {
  const dirs = [];
  const base = path.join(RESOURCES, "Base", "modules");
  for (const name of fs.readdirSync(base)) dirs.push(path.join(base, name));
  const dlc = path.join(RESOURCES, "DLC");
  if (fs.existsSync(dlc)) for (const name of fs.readdirSync(dlc).sort()) dirs.push(path.join(dlc, name, "modules"));
  return dirs.filter((d) => fs.existsSync(d) && fs.statSync(d).isDirectory());
}

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(p, out);
    else if (/\.xml$/i.test(entry.name)) out.push(p);
  }
  return out;
}

// Each <Row>/<Replace> element of a text file whose Tag is an agenda key, as [locale, element text]. The en_us
// files use <Row Tag> with the language implied; the l10n files use <Replace Tag Language>.
function agendaRows(file) {
  const text = fs.readFileSync(file, "utf8");
  if (!text.includes("LOC_DIPLOMACY_AGENDA_")) return [];
  const out = [];
  const re = /<(Row|Replace)\s+([^>]*?)>([\s\S]*?)<\/\1>/g;
  let m;
  while ((m = re.exec(text))) {
    const attrs = m[2];
    const tag = (attrs.match(/Tag="([^"]+)"/) || [])[1];
    if (!tag || !TAG.test(tag)) continue;
    const lang = (attrs.match(/Language="([^"]+)"/) || [])[1] || "en_US";
    out.push([lang, tag, `<Replace Tag="${tag}" Language="${lang}">${m[3]}</Replace>`]);
  }
  return out;
}

export function buildAgendaText() {
  const byLocale = new Map();
  for (const dir of moduleDirs()) {
    for (const file of walk(dir)) {
      for (const [lang, tag, element] of agendaRows(file)) {
        if (!byLocale.has(lang)) byLocale.set(lang, new Map());
        byLocale.get(lang).set(tag, element);
      }
    }
  }
  return byLocale;
}

function write(byLocale) {
  fs.rmSync(OUT_DIR, { recursive: true, force: true });
  fs.mkdirSync(OUT_DIR, { recursive: true });
  for (const [lang, rows] of [...byLocale].sort()) {
    const body = [...rows].sort().map(([, element]) => `    ${element.replace(/\n\s*/g, "")}`).join("\n");
    const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/setup-copy/build-agenda-text.mjs; don't edit by hand. The game's agenda text for the shell. -->
<Database>
  <LocalizedText>
${body}
  </LocalizedText>
</Database>
`;
    fs.writeFileSync(path.join(OUT_DIR, `${lang}.xml`), xml);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const byLocale = buildAgendaText();
  write(byLocale);
  const en = byLocale.get("en_US") || new Map();
  console.log(`wrote ${byLocale.size} locales to text/agenda; en_US holds ${en.size} rows, `
    + `${[...en.keys()].filter((t) => t.endsWith("_NAME")).length} agendas`);
}
