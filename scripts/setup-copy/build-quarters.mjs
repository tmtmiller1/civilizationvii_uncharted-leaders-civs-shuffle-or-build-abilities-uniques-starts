// data/setup-copy/setup-copy-quarters.sql: LShufSetup_UniqueQuarters, each unique quarter with its two buildings, for
// the civ select's rows when civics move one civic at a time (CONTRACTS 21): a quarter's row follows its buildings.
// Antiquity from the saved compiled database (tests/fixtures/source-db), Exploration and Modern from the game's data
// files for those ages. Run: node scripts/setup-copy/build-quarters.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { DatabaseSync } from "node:sqlite";
import { ageSource } from "../mapping/civ-age-source.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const OUT = path.join(ROOT, "data/setup-copy/setup-copy-quarters.sql");
const SQL = "SELECT UniqueQuarterType, BuildingType1, BuildingType2 FROM UniqueQuarters ORDER BY 1";
const q = (v) => `'${String(v).replace(/'/g, "''")}'`;

const rows = new Map();
const take = (db) => {
  for (const r of db.prepare(SQL).all()) rows.set(r.UniqueQuarterType, [r.BuildingType1, r.BuildingType2]);
};
const fixture = new DatabaseSync(path.join(ROOT, "tests/fixtures/source-db/gameplay-copy.sqlite"), { readOnly: true });
take(fixture);
fixture.close();
for (const age of ["AGE_EXPLORATION", "AGE_MODERN"]) take(ageSource(age).db);
const lines = [...rows].sort(([a], [b]) => (a < b ? -1 : 1)).map(([t, [b1, b2]]) => `  (${q(t)}, ${q(b1)}, ${q(b2)})`);
fs.writeFileSync(OUT, [
  "-- Generated by scripts/setup-copy/build-quarters.mjs; don't edit by hand. Each unique quarter with its two",
  "-- buildings (CONTRACTS 21). Loads after setup-copy-civ.sql.",
  "", "DELETE FROM LShufSetup_UniqueQuarters;",
  `INSERT INTO LShufSetup_UniqueQuarters (QuarterType, BuildingType1, BuildingType2) VALUES\n${lines.join(",\n")};`, ""
].join("\n"));
console.log(`wrote ${rows.size} quarters to ${path.relative(ROOT, OUT)}`);
