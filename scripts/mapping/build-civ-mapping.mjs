// Builds data/mapping/lshuf-civ-mapping.sql (LShufCivMapping, LShufCivMappingModifiers) and
// data/mapping/CIV-REVIEW.md from scripts/mapping/civ-draft.mjs against the game's data, then merges dependent
// bullets the way scripts/mapping/merge-pieces.mjs does for leaders.
//
//   node scripts/mapping/build-civ-mapping.mjs [--gameplay PATH] [--loc PATH]
//
// Sources default to tests/fixtures/source-db/. An Antiquity civilization's ability is read from the gameplay
// database; an Exploration or Modern one's from its own age's modules (scripts/mapping/civ-age-source.mjs), since
// the Antiquity database holds only Antiquity's rows. The description key is the civilization's own:
// Traits.Description, or the per-age key (_AQ_/_EX_/_MO_DESCRIPTION) when that's the one the text holds.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { DatabaseSync } from "node:sqlite";
import { splitBullets } from "../../shared/lshuf-text.js";
import { biasTableOfTag, joinTags } from "../../shared/lshuf-constants.js";
import { CIV_DRAFT } from "./civ-draft.mjs";
import { abilityInAge } from "./civ-age-source.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const args = process.argv.slice(2);
const argOf = (name, fallback) => (args.includes(name) ? args[args.indexOf(name) + 1] : fallback);
const SOURCE = path.join(ROOT, "tests", "fixtures", "source-db");
const GAMEPLAY = argOf("--gameplay", path.join(SOURCE, "gameplay-copy.sqlite"));
const LOC = argOf("--loc", path.join(SOURCE, "localization-copy.sqlite"));
const OUT_SQL = path.join(ROOT, "data", "mapping", "lshuf-civ-mapping.sql");
const OUT_MD = path.join(ROOT, "data", "mapping", "CIV-REVIEW.md");

const AGE_SUFFIX = { AGE_ANTIQUITY: "AQ", AGE_EXPLORATION: "EX", AGE_MODERN: "MO" };
const REQ_WORD_TAGS = {
  REQUIREMENT_PLOT_IS_COASTAL_LAND: "COAST",
  REQUIREMENT_PLOT_ADJACENT_TO_COAST: "COAST",
  REQUIREMENT_PLOT_IS_COAST: "COAST",
  REQUIREMENT_PLOT_IS_LAKE: "LAKE",
  REQUIREMENT_PLOT_ADJACENT_TO_LAKE: "LAKE",
  REQUIREMENT_PLOT_IS_RIVER: "RIVER",
  REQUIREMENT_PLOT_IS_NATURAL_WONDER: "NATURAL_WONDER",
  REQUIREMENT_PLAYER_DISCOVERED_NATURAL_WONDER: "NATURAL_WONDER",
  REQUIREMENT_CITY_IS_ISLAND: "ISLAND"
};
const BIAS_PREFIX = /^(BIOME|TERRAIN|FEATURE_CLASS|RESOURCE)_/;

const CREATE = `-- Generated by scripts/mapping/build-civ-mapping.mjs from scripts/mapping/civ-draft.mjs. Don't edit by hand.
-- The civilization mapping (CONTRACTS 14, 16): each civilization ability's bullets and the modifiers behind them,
-- matched by the modifiers' effects, arguments and requirements against the bullet text of the civilization's own
-- age (the Antiquity database for Antiquity civilizations, the age modules for Exploration and Modern ones). Bullets
-- one effect serves together are merged (BulletCount > 1). A Movable 0 row ("No effect:" or "Home only:" in its note)
-- stays with its civilization and is never dealt. INSERT OR IGNORE only, no foreign
-- keys to game tables, so this file runs in both the gameplay and the config database and can run twice.
CREATE TABLE IF NOT EXISTS LShufCivMapping (
  PieceId TEXT NOT NULL PRIMARY KEY,
  CivilizationType TEXT NOT NULL,
  Age TEXT,
  AbilityTrait TEXT NOT NULL,
  DescriptionKey TEXT,
  Kind TEXT NOT NULL,
  BulletIndex INTEGER,
  BulletCount INTEGER NOT NULL DEFAULT 1,
  BulletText TEXT,
  BiasTags TEXT,
  Value INTEGER NOT NULL DEFAULT 1,
  SpecificTo TEXT,
  Movable INTEGER NOT NULL DEFAULT 1,
  Reviewed INTEGER NOT NULL DEFAULT 1,
  Guess INTEGER NOT NULL DEFAULT 1,
  Note TEXT
);
CREATE TABLE IF NOT EXISTS LShufCivMappingModifiers (
  PieceId TEXT NOT NULL,
  ModifierId TEXT NOT NULL,
  Role TEXT NOT NULL,
  PRIMARY KEY (PieceId, ModifierId)
);
`;

const sqlValue = (v) => (v == null ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
function insertRows(table, columns, rows, chunk = 40) {
  const out = [];
  for (let i = 0; i < rows.length; i += chunk) {
    const part = rows.slice(i, i + chunk);
    out.push(`INSERT OR IGNORE INTO ${table} (${columns.join(", ")}) VALUES\n${part
      .map((r) => `  (${columns.map((c) => sqlValue(r[c])).join(", ")})`).join(",\n")};`);
  }
  return out.join("\n");
}

// --- reading the game ---

function readCivs(g, l) {
  const rows = g.prepare(`SELECT c.CivilizationType civ, ct.TraitType trait, t.Description descKey,
      (SELECT MIN(Age) FROM LegacyCivilizations lc WHERE lc.CivilizationType = c.CivilizationType) age
    FROM Civilizations c JOIN CivilizationTraits ct ON ct.CivilizationType = c.CivilizationType AND ct.TraitType LIKE 'TRAIT_%_ABILITY'
    JOIN Traits t ON t.TraitType = ct.TraitType ORDER BY c.CivilizationType`).all();
  const text = l.prepare("SELECT Text FROM LocalizedText WHERE Language = 'en_US' AND Tag = ?");
  return rows.map((r) => {
    const keys = [r.descKey, `LOC_${r.trait}_${AGE_SUFFIX[r.age] || "AQ"}_DESCRIPTION`].filter(Boolean);
    const key = keys.find((k) => text.get(k)?.Text) || r.descKey;
    const english = text.get(key)?.Text || "";
    return { ...r, descKey: key, english, bullets: splitBullets(english).bullets };
  });
}

// The bias tags a modifier's arguments and requirements carry: args [{ value }], reqs [{ type, args: "a=b;c=d" }].
function tagsFrom(args, reqs) {
  const tags = new Set();
  const consider = (v) => {
    for (const part of String(v || "").split(/[,;= ]/)) if (BIAS_PREFIX.test(part) && biasTableOfTag(part)) tags.add(part);
  };
  for (const a of args) consider(a.value);
  for (const r of reqs) {
    if (REQ_WORD_TAGS[r.type]) tags.add(REQ_WORD_TAGS[r.type]);
    if (r.type === "REQUIREMENT_PLOT_ADJACENT_TO_RIVER") tags.add(/Navigable=true/i.test(r.args || "") ? "TERRAIN_NAVIGABLE_RIVER" : "RIVER");
    consider(r.args);
  }
  return [...tags];
}

// An Antiquity civilization's ability from the gameplay database: { mods, tagsOf }.
function readModifiers(g, trait) {
  const mods = g.prepare("SELECT ModifierId FROM TraitModifiers WHERE TraitType = ? ORDER BY ModifierId").all(trait).map((r) => r.ModifierId);
  const argRows = g.prepare("SELECT Value value FROM ModifierArguments WHERE ModifierId = ?");
  const sets = g.prepare("SELECT OwnerRequirementSetId o, SubjectRequirementSetId s FROM Modifiers WHERE ModifierId = ?");
  const reqs = g.prepare(`SELECT r.RequirementType type, (SELECT group_concat(ra.Name || '=' || ra.Value, ';') FROM RequirementArguments ra
    WHERE ra.RequirementId = r.RequirementId) args FROM RequirementSetRequirements rsr JOIN Requirements r ON r.RequirementId = rsr.RequirementId
    WHERE rsr.RequirementSetId = ?`);
  const tagsOf = (id) => {
    const s = sets.get(id);
    return tagsFrom(argRows.all(id), [s?.o, s?.s].filter(Boolean).flatMap((setId) => reqs.all(setId)));
  };
  return { mods, tagsOf };
}

// An Exploration or Modern civilization's ability from its own age's modules: the same shape.
function readAgeModifiers(age, trait) {
  const ability = abilityInAge(age, trait);
  const tagsOf = (id) => {
    const m = ability.modifier(id);
    if (!m) return [];
    const reqs = [...m.owner, ...m.subject].map((r) => ({ type: r.type, args: r.args.map((a) => `${a.name}=${a.value}`).join(";") }));
    return tagsFrom(m.args, reqs);
  };
  return { mods: ability.mods, tagsOf };
}

const liveAbility = (g, rec) => (rec.age && rec.age !== "AGE_ANTIQUITY" ? readAgeModifiers(rec.age, rec.trait) : readModifiers(g, rec.trait));

// --- building ---

function buildCiv(rec, draft, live) {
  const out = { rec, pieces: [], unplaced: [], problems: [] };
  const entry = Array.isArray(draft) ? { bullets: draft } : draft || null;
  if (!entry) {
    out.problems.push("No draft entry.");
    out.unplaced.push(...live.mods.map((id) => ({ id, why: "No draft entry." })));
    return out;
  }
  if (entry.bullets.length !== rec.bullets.length) {
    out.problems.push(`Draft has ${entry.bullets.length} bullets, the text has ${rec.bullets.length}.`);
  }
  const assigned = new Map();
  entry.bullets.forEach((b, i) => {
    const n = i + 1;
    const pid = `${rec.civ}__B${String(n).padStart(2, "0")}`;
    const modifiers = [...(b.mods || []).map((id) => ({ id, role: "effect" })), ...(b.hidden || []).map((id) => ({ id, role: "hidden" }))];
    for (const m of modifiers) {
      if (!live.mods.includes(m.id)) out.problems.push(`${pid}: ${m.id} isn't on the live ability.`);
      else if (assigned.has(m.id)) out.problems.push(`${m.id} is drafted twice.`);
      else assigned.set(m.id, pid);
    }
    const dataTags = [...new Set(modifiers.flatMap((m) => live.tagsOf(m.id)))];
    const drafted = (b.bias || []).filter((t) => !dataTags.includes(t));
    out.pieces.push({
      PieceId: pid, CivilizationType: rec.civ, Age: rec.age, AbilityTrait: rec.trait, DescriptionKey: rec.descKey,
      Kind: "bullet", BulletIndex: n, BulletCount: 1, BulletText: rec.bullets[i] || null,
      BiasTags: joinTags([...dataTags, ...drafted]), Value: b.value, SpecificTo: null,
      Movable: b.movable === 0 ? 0 : 1, Reviewed: 1, Guess: modifiers.length ? 1 : 0, Note: b.note || null,
      why: b.why, modifiers, dataTags, drafted, keep: Boolean(b.keep)
    });
  });
  const unplacedWhy = (id) => (typeof entry.unplacedWhy === "object" ? entry.unplacedWhy[id] : entry.unplacedWhy) || "Drafted as unplaced.";
  for (const id of live.mods) {
    if (assigned.has(id)) continue;
    const why = (entry.unplaced || []).includes(id) ? unplacedWhy(id) : "Not drafted into any bullet.";
    if (!(entry.unplaced || []).includes(id)) out.problems.push(`${id} isn't in any bullet and isn't listed as unplaced.`);
    out.unplaced.push({ id, why });
  }
  return out;
}

// A Movable 0 bullet with modifiers behind it joins the nearest earlier bullet (one effect serves both); a "No
// effect:" row has nothing behind it and stays as it is, undealt, and so does a row drafted with keep (the wonder
// favor, which has a modifier of its own that only works at home).
function mergeDependents(built) {
  const merged = [];
  for (const c of built) {
    for (let i = c.pieces.length - 1; i > 0; i--) {
      const d = c.pieces[i];
      if (d.Movable !== 0 || !d.modifiers.length || d.keep) continue;
      const t = c.pieces[i - 1];
      if (Number(t.BulletIndex) + Number(t.BulletCount) !== Number(d.BulletIndex)) continue;
      t.BulletCount += 1;
      t.BulletText = `${t.BulletText}[N]${d.BulletText}`;
      t.BiasTags = joinTags([...new Set([...(t.BiasTags || "").split("|"), ...(d.BiasTags || "").split("|")].filter(Boolean))]);
      t.modifiers.push(...d.modifiers);
      t.Note = `${t.Note ? `${t.Note} ` : ""}Bullet ${d.BulletIndex} merged in: one effect serves both.`;
      c.pieces.splice(i, 1);
      merged.push(`${d.PieceId} -> ${t.PieceId}`);
    }
  }
  return merged;
}

function review(built, merged) {
  const lines = [
    "# Civilization mapping review list", "",
    `Built ${new Date().toISOString().slice(0, 10)} by scripts/mapping/build-civ-mapping.mjs from scripts/mapping/civ-draft.mjs`,
    "against the game's data as each civilization's own age loads it (the Antiquity gameplay database in",
    "tests/fixtures/source-db/ for Antiquity civilizations, the age modules read by scripts/mapping/civ-age-source.mjs",
    "for Exploration and Modern ones). Each bullet of each civilization ability is matched to the modifiers that do it",
    "by their effects, arguments and requirements. A \"No effect:\" row is a rule the text states that has no modifier",
    "on the ability; a \"Home only:\" row (the wonder favor) has a modifier that only fires for the civilization's own",
    "base trait. Both keep Movable 0 and stay with their civilization. Every row ships Reviewed = 1.", "",
    `Merged pieces: ${merged.length ? merged.join(", ") : "none"}.`, ""
  ];
  for (const c of built) {
    lines.push(`## ${c.rec.civ} (${c.rec.age || "no age"}, ${c.rec.trait}, text ${c.rec.descKey})`, "");
    for (const p of c.problems) lines.push(`- PROBLEM: ${p}`);
    for (const p of c.pieces) {
      lines.push(`- ${p.PieceId} (value ${p.Value}${p.Movable ? "" : ", not movable"}): ${String(p.BulletText || "").replace(/\[[^\]]*\]/g, "").slice(0, 160)}`);
      lines.push(`  - Why: ${p.why}`);
      if (p.modifiers.length) lines.push(`  - Modifiers: ${p.modifiers.map((m) => `${m.id}${m.role === "hidden" ? " (hidden)" : ""}`).join(", ")}`);
      if (p.BiasTags) lines.push(`  - BiasTags: ${p.BiasTags}${p.drafted.length ? ` (from the text: ${p.drafted.join(", ")})` : ""}`);
      if (p.Note) lines.push(`  - Note: ${p.Note}`);
    }
    for (const u of c.unplaced) lines.push(`- Unplaced: ${u.id}. ${u.why}`);
    lines.push("");
  }
  return lines.join("\n");
}

function main() {
  const g = new DatabaseSync(GAMEPLAY, { readOnly: true });
  const l = new DatabaseSync(LOC, { readOnly: true });
  const built = readCivs(g, l).map((rec) => buildCiv(rec, CIV_DRAFT[rec.civ], liveAbility(g, rec)));
  const merged = mergeDependents(built);
  const pieceCols = ["PieceId", "CivilizationType", "Age", "AbilityTrait", "DescriptionKey", "Kind", "BulletIndex", "BulletCount",
    "BulletText", "BiasTags", "Value", "SpecificTo", "Movable", "Reviewed", "Guess", "Note"];
  const pieces = built.flatMap((c) => c.pieces);
  const modRows = pieces.flatMap((p) =>
    p.modifiers.map((m) => ({ PieceId: p.PieceId, ModifierId: m.id, Role: m.role })));
  fs.writeFileSync(OUT_SQL, [CREATE, insertRows("LShufCivMapping", pieceCols, pieces), "",
    insertRows("LShufCivMappingModifiers", ["PieceId", "ModifierId", "Role"], modRows), ""].join("\n"));
  fs.writeFileSync(OUT_MD, review(built, merged));
  const problems = built.flatMap((c) => c.problems.map((p) => `${c.rec.civ}: ${p}`));
  const placed = modRows.length;
  const unplaced = built.reduce((n, c) => n + c.unplaced.length, 0);
  console.log(`civs ${built.length}, pieces ${pieces.length}, modifiers placed ${placed}, unplaced ${unplaced}, `
    + `merged ${merged.length}`);
  for (const age of ["AGE_ANTIQUITY", "AGE_EXPLORATION", "AGE_MODERN"]) {
    const cs = built.filter((c) => c.rec.age === age);
    const ps = cs.flatMap((c) => c.pieces);
    console.log(`  ${age}: civs ${cs.length}, pieces ${ps.length}, movable ${ps.filter((p) => p.Movable).length}, `
      + `modifiers placed ${ps.reduce((n, p) => n + p.modifiers.length, 0)}, unplaced ${cs.reduce((n, c) => n + c.unplaced.length, 0)}`);
  }
  for (const p of problems) console.log(`PROBLEM ${p}`);
  g.close();
  l.close();
  if (problems.length) process.exitCode = 1;
}

main();
