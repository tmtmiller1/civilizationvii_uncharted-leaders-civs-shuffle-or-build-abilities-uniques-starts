// Builds data/mapping/lshuf-civ-links.sql (CONTRACTS 23, docs/DEPENDENCIES.md): the links between dealt
// civilization items that only a modifier states, read from each age's data through civ-age-source.mjs.
//
//   node scripts/mapping/build-deps.mjs            write the file
//   node scripts/mapping/build-deps.mjs --check    exit 1 when the file differs from what the data gives
//   node scripts/mapping/build-deps.mjs --report   print the whole breakdown (every link, shipped or live)
//
// LShufCivLinks: a tradition whose modifiers name a unique improvement, building or quarter that another civic of
// the same civilization's tree unlocks; the tradition's civic needs that civic (a quarter counts by the civic that
// unlocks its BuildingType1, as R1 does).
// LShufBoundModifiers: a modifier on a civilization's ability whose own subject requirements name exactly one of
// that civilization's uniques: a city founded by its unit, a tag only that unit family carries, a city with its
// building or quarter. The anchor is the unit family's base, the building or the quarter.
// The structural links (quarters, great people, builder units) aren't written here: the deal reads them live.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { AGES, abilityInAge, ageSource, civsOfAge } from "./civ-age-source.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
export const OUT = path.join(ROOT, "data/mapping/lshuf-civ-links.sql");

const HEADER = `-- Links between dealt civilization items that the game's tables don't state directly, found by walking modifiers
-- (CONTRACTS 23, docs/DEPENDENCIES.md). Generated by scripts/mapping/build-deps.mjs from the 1.5.1 data; the
-- structural links (quarters, great people, builder units) are read live at game load instead. INSERT OR IGNORE only,
-- no foreign keys: a row whose types a player's database lacks is skipped where it's read.
CREATE TABLE IF NOT EXISTS LShufCivLinks (
  NodeType TEXT NOT NULL,
  NeedsNodeType TEXT NOT NULL,
  Why TEXT,
  PRIMARY KEY (NodeType, NeedsNodeType)
);
CREATE TABLE IF NOT EXISTS LShufBoundModifiers (
  ModifierId TEXT NOT NULL PRIMARY KEY,
  AnchorType TEXT NOT NULL,
  Why TEXT,
  ByPiece TEXT
);
CREATE TABLE IF NOT EXISTS LShufBoundPieces (
  PieceId TEXT NOT NULL PRIMARY KEY,
  AnchorType TEXT NOT NULL,
  Why TEXT
);
CREATE TABLE IF NOT EXISTS LShufCivUnitLinks (
  UnitType TEXT NOT NULL PRIMARY KEY,
  NodeType TEXT NOT NULL,
  Why TEXT
);`;

