const all = (db, sql, ...p) => {
  try {
    return db.prepare(sql).all(...p);
  } catch {
    return [];
  }
};
const CIVIC_TREE = (t) => t && t.startsWith("TREE_CIVICS_") && !t.endsWith("_MAIN");

// What one civilization of `age` owns: unit families by base, buildings, quarters, improvements, traditions, and the
// civic of its own tree that unlocks each.
function civOwn(db, base) {
  const units = all(db, "SELECT UnitType FROM Units WHERE TraitType = ? ORDER BY UnitType", base).map((r) => r.UnitType);
  const familyOf = new Map();
  for (const u of units) {
    const b = units.filter((p) => u === p || u.startsWith(`${p}_`)).sort((x, y) => x.length - y.length)[0];
    familyOf.set(u, b);
  }
  const buildings = new Set(all(db, "SELECT ConstructibleType t FROM Buildings WHERE TraitType = ?", base).map((r) => r.t));
  const improvements = new Set(all(db, "SELECT ConstructibleType t FROM Improvements WHERE TraitType = ?", base).map((r) => r.t));
  const quarters = new Map(all(db, "SELECT * FROM UniqueQuarters WHERE TraitType = ?", base).map((r) => [r.UniqueQuarterType, r]));
  const traditions = all(db, "SELECT TraditionType t FROM Traditions WHERE TraitType = ? ORDER BY TraditionType", base).map((r) => r.t);
  const nodeOf = new Map();
  for (const r of all(db, `SELECT u.ProgressionTreeNodeType node, u.TargetType target, n.ProgressionTree tree
      FROM ProgressionTreeNodeUnlocks u JOIN ProgressionTreeNodes n ON n.ProgressionTreeNodeType = u.ProgressionTreeNodeType
      ORDER BY u.ProgressionTreeNodeType`)) {
    if (CIVIC_TREE(r.tree) && !nodeOf.has(r.target)) nodeOf.set(r.target, r.node);
  }
  const tagOwner = new Map();
  for (const t of all(db, "SELECT Tag, group_concat(Type, ',') types FROM TypeTags GROUP BY Tag")) {
    const fams = new Set(t.types.split(",").map((x) => familyOf.get(x) || "OTHER"));
    if (fams.size === 1 && !fams.has("OTHER")) tagOwner.set(t.Tag, [...fams][0]);
  }
  const unlockNode = (type) => {
    if (quarters.has(type)) return nodeOf.get(quarters.get(type).BuildingType1);
    return nodeOf.get(type);
  };
  return { familyOf, buildings, improvements, quarters, traditions, nodeOf, tagOwner, unlockNode };
}

// The unique a subject requirement names, or null.
function anchorOf(req, own) {
  const arg = (name) => (req.args.find((a) => a.name === name) || {}).value;
  switch (req.type) {
    case "REQUIREMENT_CITY_FOUNDED_BY_UNIT_TYPE": return own.familyOf.get(arg("UnitType")) || null;
    case "REQUIREMENT_UNIT_TAG_MATCHES": return own.tagOwner.get(arg("Tag")) || null;
    // 1.5.1's Saga Hero grant names Iceland's Thing (an improvement) through BuildingType.
    case "REQUIREMENT_CITY_HAS_BUILDING": {
      const t = arg("BuildingType");
      return own.buildings.has(t) || own.improvements.has(t) ? t : null;
    }
    case "REQUIREMENT_CITY_HAS_UNIQUE_QUARTER":
    case "REQUIREMENT_PLOT_UNIQUE_QUARTER": return own.quarters.has(arg("UniqueQuarterType")) ? arg("UniqueQuarterType") : null;
    default: return null;
  }
}

const WHY = {
  REQUIREMENT_CITY_FOUNDED_BY_UNIT_TYPE: (a, inv) => `city ${inv ? "not " : ""}founded by ${a}`,
  REQUIREMENT_UNIT_TAG_MATCHES: (a, inv, tag) => `units ${inv ? "not " : ""}tagged ${tag}`,
  REQUIREMENT_CITY_HAS_BUILDING: (a, inv) => `city ${inv ? "lacks" : "has"} ${a}`,
  REQUIREMENT_CITY_HAS_UNIQUE_QUARTER: (a, inv) => `city ${inv ? "lacks" : "has"} ${a}`,
  REQUIREMENT_PLOT_UNIQUE_QUARTER: (a, inv) => `plot ${inv ? "outside" : "in"} ${a}`
};

// A modifier's subject requirements, and those of the modifiers it attaches (1.5.1 grants the Alim through an
// attached modifier whose plot requirement names the Ulema).
function subjectReqs(source, m) {
  const out = [...(m.subject || [])];
  if (m.effect === "EFFECT_ATTACH_MODIFIERS") {
    for (const a of m.args || []) {
      const sub = a.name === "ModifierId" ? source.modifier(a.value) : null;
      if (sub) out.push(...(sub.subject || []));
    }
  }
  return out;
}

// A civic of the civ's own tree whose modifier names one of the civ's unit families in a UnitType argument (Sengoku's
// Kinsei lets its holder train the tier 2 Samurai, and switches Man-at-Arms off): the family belongs to that civic
// (CONTRACTS 23 R1). family base -> { node, why }.
function civicUnitLinks(db, source, own) {
  const out = new Map();
  for (const r of all(db, `SELECT u.ProgressionTreeNodeType node, u.TargetType mod, n.ProgressionTree tree
      FROM ProgressionTreeNodeUnlocks u JOIN ProgressionTreeNodes n ON n.ProgressionTreeNodeType = u.ProgressionTreeNodeType
      WHERE u.TargetKind = 'KIND_MODIFIER' ORDER BY 1, 2`)) {
    if (!CIVIC_TREE(r.tree)) continue;
    const m = source.modifier(r.mod);
    for (const a of (m && m.args) || []) {
      const fam = a.name === "UnitType" ? own.familyOf.get(a.value) : null;
      if (fam && !out.has(fam)) out.set(fam, { node: r.node, why: `${r.mod} names ${a.value}` });
    }
  }
  return out;
}

export function buildDeps() {
  const links = [];
  const bound = [];
  const unitLinks = [];
  for (const age of AGES) {
    const { db, source } = ageSource(age);
    for (const { civ, trait } of civsOfAge(age)) {
      const base = trait.slice(0, -"_ABILITY".length);
      const own = civOwn(db, base);
      // Bound modifiers.
      for (const id of [...abilityInAge(age, trait).mods].sort()) {
        const m = source.modifier(id);
        if (!m) continue;
        const hits = subjectReqs(source, m).map((r) => ({ r, a: anchorOf(r, own) })).filter((h) => h.a);
        const anchors = new Set(hits.map((h) => h.a));
        if (anchors.size !== 1) continue;
        const h = hits[0];
        const tag = (h.r.args.find((x) => x.name === "Tag") || {}).value;
        bound.push({ age, civ, ModifierId: id, AnchorType: h.a, Why: WHY[h.r.type](h.a, h.r.inverse, tag) });
      }
      for (const [unit, l] of civicUnitLinks(db, source, own)) {
        unitLinks.push({ age, civ, UnitType: unit, NodeType: l.node, Why: l.why });
      }
      // Tradition links.
      const seen = new Set();
      for (const trad of own.traditions) {
        const from = own.nodeOf.get(trad);
        if (!from) continue;
        const mods = all(db, "SELECT ModifierId FROM TraditionModifiers WHERE TraditionType = ? ORDER BY ModifierId", trad);
        for (const { ModifierId } of mods) {
          for (const v of source.reach(ModifierId)) {
            const value = v.value;
            if (!(own.improvements.has(value) || own.buildings.has(value) || own.quarters.has(value))) continue;
            const to = own.unlockNode(value);
            if (!to || to === from || seen.has(`${from}|${to}`)) continue;
            seen.add(`${from}|${to}`);
            links.push({ age, civ, NodeType: from, NeedsNodeType: to, Why: `${trad} needs ${value}` });
          }
        }
      }
    }
  }
  for (const bp of BOUND_PIECES) {
    for (const id of bp.mods) {
      if (!bound.find((b) => b.ModifierId === id)) {
        bound.push({ age: bp.age, civ: bp.civ, ModifierId: id, AnchorType: bp.anchor, Why: bp.why, ByPiece: bp.piece });
      }
    }
  }
  const pieces = BOUND_PIECES.map((bp) => ({
    age: bp.age, civ: bp.civ, PieceId: bp.piece, AnchorType: bp.anchor, Why: bp.why
  }));
  const order = (a, b) => AGES.indexOf(a.age) - AGES.indexOf(b.age) || a.civ.localeCompare(b.civ);
  pieces.sort((a, b) => order(a, b) || a.PieceId.localeCompare(b.PieceId));
  links.sort((a, b) => order(a, b) || a.NodeType.localeCompare(b.NodeType)
    || a.NeedsNodeType.localeCompare(b.NeedsNodeType));
  bound.sort((a, b) => order(a, b) || a.ModifierId.localeCompare(b.ModifierId));
  unitLinks.sort((a, b) => order(a, b) || a.UnitType.localeCompare(b.UnitType));
  return { links, bound, pieces, unitLinks };
}

const sq = (v) => `'${String(v).replace(/'/g, "''")}'`;

export function renderDeps({ links, bound, pieces = [], unitLinks = [] }) {
  const out = [HEADER];
  if (links.length) {
    out.push("INSERT OR IGNORE INTO LShufCivLinks (NodeType, NeedsNodeType, Why) VALUES");
    out.push(`${links.map((l) => `  (${sq(l.NodeType)}, ${sq(l.NeedsNodeType)}, ${sq(l.Why)})`).join(",\n")};`);
  }
  if (bound.length) {
    out.push("INSERT OR IGNORE INTO LShufBoundModifiers (ModifierId, AnchorType, Why, ByPiece) VALUES");
    out.push(`${bound.map((b) => `  (${sq(b.ModifierId)}, ${sq(b.AnchorType)}, ${sq(b.Why)}, ${b.ByPiece ? sq(b.ByPiece) : "NULL"})`)
      .join(",\n")};`);
  }
  if (pieces.length) {
    out.push("INSERT OR IGNORE INTO LShufBoundPieces (PieceId, AnchorType, Why) VALUES");
    out.push(`${pieces.map((b) => `  (${sq(b.PieceId)}, ${sq(b.AnchorType)}, ${sq(b.Why)})`).join(",\n")};`);
  }
  if (unitLinks.length) {
    out.push("INSERT OR IGNORE INTO LShufCivUnitLinks (UnitType, NodeType, Why) VALUES");
    out.push(`${unitLinks.map((l) => `  (${sq(l.UnitType)}, ${sq(l.NodeType)}, ${sq(l.Why)})`).join(",\n")};`);
  }
  return `${out.join("\n")}\n`;
}

// The full breakdown docs/DEPENDENCIES.md describes: the shipped links, then the structural ones the deal reads live.
function report(deps) {
  const lines = ["Tradition links (LShufCivLinks):"];
  for (const l of deps.links) lines.push(`  [${l.age.slice(4)}] ${l.NodeType} needs ${l.NeedsNodeType}: ${l.Why}`);
  lines.push("Bound modifiers (LShufBoundModifiers):");
  for (const b of deps.bound) lines.push(`  [${b.age.slice(4)}] ${b.civ} ${b.ModifierId} -> ${b.AnchorType}: ${b.Why}`);
  lines.push("Unit families that belong to a civic (LShufCivUnitLinks):");
  for (const l of deps.unitLinks) lines.push(`  [${l.age.slice(4)}] ${l.civ} ${l.UnitType} goes with ${l.NodeType}: ${l.Why}`);
  lines.push("Read live at game load (CONTRACTS 23 R1-R3):");
  for (const age of AGES) {
    const { db } = ageSource(age);
    for (const { civ, trait } of civsOfAge(age)) {
      const own = civOwn(db, trait.slice(0, -"_ABILITY".length));
      for (const q of own.quarters.values()) {
        const a = own.nodeOf.get(q.BuildingType1);
        const b = own.nodeOf.get(q.BuildingType2);
        if (a && b && a !== b) lines.push(`  [${age.slice(4)}] ${civ} quarter ${q.UniqueQuarterType}: ${a} + ${b}`);
      }
      for (const g of all(db, "SELECT GreatPersonClassType, UnitType, UniqueQuarterType, ConstructibleType FROM GreatPersonClasses")) {
        const fam = own.familyOf.get(g.UnitType);
        if (!fam) continue;
        const need = g.UniqueQuarterType && own.quarters.has(g.UniqueQuarterType) ? g.UniqueQuarterType
          : g.ConstructibleType && own.nodeOf.has(g.ConstructibleType) ? g.ConstructibleType : null;
        if (need) lines.push(`  [${age.slice(4)}] ${civ} great person ${fam} needs ${need} (${own.unlockNode(need)})`);
      }
      for (const r of all(db, "SELECT UnitType, ConstructibleType FROM Unit_BuildConstructibles")) {
        if (!own.improvements.has(r.ConstructibleType) || !own.familyOf.has(r.UnitType)) continue;
        const builders = all(db, "SELECT UnitType FROM Unit_BuildConstructibles WHERE ConstructibleType = ?", r.ConstructibleType);
        if (builders.length === 1) lines.push(`  [${age.slice(4)}] ${civ} ${r.ConstructibleType} only built by ${r.UnitType}`);
      }
    }
  }
  return lines.join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const deps = buildDeps();
  const text = renderDeps(deps);
  if (args.includes("--report")) {
    console.log(report(deps));
  } else if (args.includes("--check")) {
    const same = fs.existsSync(OUT) && fs.readFileSync(OUT, "utf8") === text;
    console.log(same ? "lshuf-civ-links.sql matches the data" : "lshuf-civ-links.sql differs from the data");
    process.exit(same ? 0 : 1);
  } else {
    fs.writeFileSync(OUT, text);
    console.log(`wrote ${path.relative(ROOT, OUT)}: ${deps.links.length} links, ${deps.bound.length} bound modifiers`);
  }
}
